import { useEffect, useState } from "react";
import type { FieldEntry, Manifest, ObjectInfo } from "../lib/bundle";
import { loadIndex, loadOptional } from "../lib/bundle";
import { navigate } from "../lib/router";
import { TopBar } from "../components/TopBar";

type VRow = { f: FieldEntry; o: ObjectInfo };

export function About() {
  const [rows, setRows] = useState<VRow[] | null>(null);
  const [credits, setCredits] = useState<string[]>([]);
  useEffect(() => {
    (async () => {
      try {
        const { index } = await loadIndex();
        const res = await Promise.all(index.fields.map(async (f) => {
          const m = await loadOptional<Manifest>(f.base + "manifest.json");
          const o = m?.objects?.includes("target") ? await loadOptional<ObjectInfo>(f.base + "objects/target.json") : null;
          return { f, m, o };
        }));
        setRows(res.filter((r): r is typeof r & { o: ObjectInfo } => !!r.o?.motion?.measured && !!r.o.motion.reference).map(({ f, o }) => ({ f, o })));
        setCredits([...new Set(res.flatMap((r) => r.m?.credits ?? []))]);
      } catch { setRows([]); }
    })();
  }, []);

  return (
    <div className="page">
      <TopBar />
      <div className="doc">
        <h1>About SkyLapse</h1>
        <p className="lede-s">SPHEREx maps the whole sky in 102 infrared colours every six months, but its own record is barely a year long — nearby worlds move
          only a pixel or two. WISE watched the same sky at the same wavelength (4.6 µm) from 2010 to 2024. SkyLapse joins both into one 16-year movie.</p>

        <h2>How it works</h2>
        <ol className="method">
          <li><b>Find the field.</b> A name or RA/Dec is resolved, and the field centre is set for the target's motion.</li>
          <li><b>Collect 16 years of images.</b> 23–48 unWISE time-resolved WISE/NEOWISE epochs per field (2010–2024) and every SPHEREx visit (2025–2026) from NASA IRSA.</li>
          <li><b>Clean them.</b> SPHEREx: zodiacal light subtracted, bad and saturated pixels flagged from the image's own flag names. WISE: saturation masked.</li>
          <li><b>Put them on one grid.</b> All images are reprojected with Astropy onto a single sky grid; SPHEREx visits are co-added per detector for better signal.</li>
          <li><b>Measure.</b> Sources are detected in WISE images and linked across 14 years (2010–2024); proper motion is fitted and compared with ESA Gaia DR3 and the published literature.</li>
          <li><b>Explain.</b> An AI copilot writes a plain-language summary in English and Azerbaijani, using only the numbers we measured.</li>
        </ol>

        <h2>Validation — measured vs. reference proper motion</h2>
        {rows === null ? <div className="skeleton-box" style={{ minHeight: 100 }} /> : rows.length === 0 ? (
          <p className="muted">The validation table appears here as soon as the measurements are in the data bundle.</p>
        ) : (
          <table className="cand-table">
            <thead><tr><th>Target</th><th>Measured (mas/yr)</th><th>Reference (mas/yr)</th><th>Source</th><th>Agreement</th></tr></thead>
            <tbody>
              {rows.map(({ f, o }) => {
                const m = o.motion!.measured!, r = o.motion!.reference!;
                return (
                  <tr key={f.field_id} onClick={() => navigate(`/view?field=${encodeURIComponent(f.field_id)}`)}>
                    <td><b>{o.name}</b></td>
                    <td className="mono">{Math.round(m.pm_total)} ± {Math.round(m.err)}</td>
                    <td className="mono">{Math.round(Math.hypot(r.pmra, r.pmdec))}</td>
                    <td>{r.source}</td>
                    <td className="mono"><b className="ok">{o.motion!.agreement_pct != null ? `${o.motion!.agreement_pct.toFixed(1)}%` : "—"}</b></td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        )}

        <h2>Data and credits</h2>
        <ul className="credits">
          <li>NASA SPHEREx — images from the NASA/IPAC Infrared Science Archive (IRSA).</li>
          <li>NASA WISE / NEOWISE — unWISE time-resolved coadds (Meisner et al.), served by byw.tools (Backyard Worlds / AMNH).</li>
          <li>ESA Gaia DR3 — positions and proper motions (Gaia Collaboration).</li>
          <li>CatWISE2020 — motions of faint infrared sources (Marocco et al.).</li>
          <li>Software: Astropy, reproject, photutils, NumPy, React, Vite.</li>
          {credits.filter((c) => !/MOCK/i.test(c)).map((c) => <li key={c} className="muted">{c}</li>)}
        </ul>

        <h2>Use of AI</h2>
        <p>Team FARAD built SkyLapse with AI coding assistants (Claude Code and others), which wrote much of the code under our direction and review.
          The copilot texts are generated by an AI model <b>only from facts our pipeline computed</b> (positions, motions, brightness); it is instructed not to add anything else.
          Any AI-generated image or audio is marked as such. We never claim discoveries: objects we flag are <i>candidates for follow-up</i>.</p>
        <p className="muted small">NASA Space Apps Challenge 2026 · Baku · challenge “Planet X and SPHEREx”. NASA does not endorse this project.</p>
      </div>
    </div>
  );
}
